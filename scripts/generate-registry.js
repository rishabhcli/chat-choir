import { readdir, writeFile } from 'node:fs/promises';
const directory=new URL('../src/synth/instruments/',import.meta.url);
const files=(await readdir(directory)).filter(x=>x.endsWith('.js')).sort();
const source=`// Generated by scripts/generate-registry.js; do not edit.\n${files.map((f,i)=>`import * as instrument${i} from './instruments/${f}';`).join('\n')}\nexport const instruments = [${files.map((_,i)=>`instrument${i}`).join(', ')}];\n`;
await writeFile(new URL('../src/synth/registry.generated.js',import.meta.url),source);
